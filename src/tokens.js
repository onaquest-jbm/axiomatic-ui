'use strict';
// Emits a derivation as tokens named for what they mean, never for how they look:
// --gap-group, not --space-12; --ink-secondary, not --gray-600. An agent choosing a token
// has to choose a meaning, which is the point.
const fs = require('fs');
const path = require('path');
const { BY_ID } = require('./principles');

function vars(d, theme) {
  const L = [];
  const t = d.type;
  L.push('  --font-ui: system-ui, -apple-system, "Segoe UI", Roboto, "Helvetica Neue", Arial, sans-serif;');
  L.push('  --font-code: ui-monospace, "Cascadia Code", "SF Mono", Menlo, Consolas, monospace;');
  for (const [k, v] of Object.entries(t.sizes)) L.push(`  --text-${k}: ${v}px;`);
  L.push(`  --weight-regular: ${t.weights.regular};`, `  --weight-strong: ${t.weights.strong};`);
  L.push(`  --leading-body: ${t.leading.body};`, `  --leading-heading: ${t.leading.heading};`, `  --measure: ${t.measure};`);
  for (const [k, v] of Object.entries(d.space)) L.push(`  --gap-${k}: ${v}px;`);
  L.push(`  --target-min: ${d.target.min}px;`, `  --target-touch: ${d.target.touch}px;`, `  --control-height: ${d.target.control}px;`);
  L.push(`  --radius-control: ${d.radius.control}px;`, `  --radius-container: ${d.radius.container}px;`);
  for (const [k, v] of Object.entries(d.motion)) L.push(`  --duration-${k}: ${v}ms;`);
  L.push('  --ease-enter: cubic-bezier(0.2, 0, 0, 1);', '  --ease-exit: cubic-bezier(0.4, 0, 1, 1);');
  L.push(`  --elevation-overlay: ${d.elevation.overlay};`);
  for (const [k, v] of Object.entries(d.z)) L.push(`  --layer-${k}: ${v};`);
  return L.concat(colorVars(d.color[theme]));
}
const colorVars = (c) => Object.entries(c).map(([k, v]) => `  --${k}: ${v};`);

function toCss(d) {
  const themes = Object.keys(d.color);
  const first = themes[0];
  const out = ['/* Generated by derive. Edit the model, not this file. Every value is explained in derivation.md. */', ':root {'];
  out.push(...vars(d, first), `  color-scheme: ${first};`, '}');
  const dark = d.color.dark;
  if (dark && first !== 'dark') {
    out.push('@media (prefers-color-scheme: dark) {', '  :root:not([data-theme="light"]) {', ...colorVars(dark).map((l) => '  ' + l), '    color-scheme: dark;', '  }', '}');
    out.push(':root[data-theme="dark"] {', ...colorVars(dark), '  color-scheme: dark;', '}');
    out.push(':root[data-theme="light"] {', ...colorVars(d.color[first]), '  color-scheme: light;', '}');
  }
  return out.join('\n') + '\n';
}

function toBaseCss() {
  return `/* Generated by derive. The floor every screen stands on. */
*, *::before, *::after { box-sizing: border-box; }
body { margin: 0; background: var(--surface-canvas); color: var(--ink-primary); font-family: var(--font-ui); font-size: var(--text-body); line-height: var(--leading-body); -webkit-font-smoothing: antialiased; }
:focus-visible { outline: 2px solid var(--focus); outline-offset: 2px; }
::selection { background: var(--selection); }
code, kbd, pre, samp { font-family: var(--font-code); }
.tabular, td, th { font-variant-numeric: tabular-nums; }
button, input, select, textarea { font: inherit; color: inherit; }
@media (prefers-reduced-motion: reduce) {
  *, *::before, *::after { animation-duration: 0.01ms !important; animation-iteration-count: 1 !important; transition-duration: 0.01ms !important; scroll-behavior: auto !important; }
}
`;
}

function toTs(d) {
  const { trace, ...rest } = d;
  return `// Generated by derive. Edit the model, not this file.\nexport const design = ${JSON.stringify(rest, null, 2)} as const;\n`;
}

function kName(k) { return String(k).replace(/[-_](\w)/g, (_, c) => c.toUpperCase()); }
function toKotlin(d, pkg = 'design') {
  const L = ['// Generated by derive. Edit the model, not this file.', `package ${pkg}`, '', 'import androidx.compose.ui.graphics.Color', 'import androidx.compose.ui.unit.dp', 'import androidx.compose.ui.unit.sp', '', 'object Derived {'];
  L.push('    object Gap {', ...Object.entries(d.space).map(([k, v]) => `        val ${kName(k)} = ${v}.dp`), '    }');
  L.push('    object Text {', ...Object.entries(d.type.sizes).map(([k, v]) => `        val ${kName(k)} = ${v}.sp`), '    }');
  L.push('    object Target {', `        val min = ${d.target.min}.dp`, `        val control = ${d.target.control}.dp`, '    }');
  L.push('    object Duration {', ...Object.entries(d.motion).map(([k, v]) => `        const val ${kName(k)} = ${v}`), '    }');
  for (const [theme, c] of Object.entries(d.color)) {
    L.push(`    object ${theme[0].toUpperCase() + theme.slice(1)} {`);
    for (const [k, v] of Object.entries(c)) L.push(`        val ${kName(k)} = Color(0xFF${v.slice(1).toUpperCase()})`);
    L.push('    }');
  }
  L.push('}');
  return L.join('\n') + '\n';
}

function toMarkdown(d) {
  const L = [`# Derivation${d.model.product ? `: ${d.model.product.name}` : ''}`, '', 'Every value below follows from the model and the principles it cites. To change a value, change the model.', ''];
  L.push('| Decision | Value | Because | Principles |', '|---|---|---|---|');
  for (const t of d.trace) {
    const v = typeof t.value === 'object' ? Object.entries(t.value).map(([k, x]) => `${k} ${x}`).join(', ') : String(t.value);
    L.push(`| ${t.key} | ${v.replace(/\|/g, '/')} | ${t.because.replace(/\|/g, '/')} | ${t.principles.map((p) => BY_ID[p] ? BY_ID[p].name : p).join('; ')} |`);
  }
  L.push('', '## Tasks', '', '| Task | Tier | Treatment |', '|---|---|---|');
  for (const t of d.tasks) L.push(`| ${t.does || t.id} | ${t.tier} | ${t.treatment.join('; ')} |`);
  return L.join('\n') + '\n';
}

function writeAll(d, outDir, opts = {}) {
  fs.mkdirSync(outDir, { recursive: true });
  const files = {
    'tokens.css': toCss(d), 'base.css': toBaseCss(), 'design.ts': toTs(d), 'Derived.kt': toKotlin(d, opts.kotlinPackage),
    'derivation.json': JSON.stringify(d, null, 2) + '\n', 'derivation.md': toMarkdown(d),
  };
  for (const [n, c] of Object.entries(files)) fs.writeFileSync(path.join(outDir, n), c);
  return Object.keys(files).map((n) => path.join(outDir, n));
}

// The names an agent may use, for the linter.
function tokenNames(d) {
  const css = toCss(d);
  return new Set([...css.matchAll(/--([a-z][a-z0-9-]*)\s*:/g)].map((m) => m[1]));
}

module.exports = { toCss, toBaseCss, toTs, toKotlin, toMarkdown, writeAll, tokenNames };
